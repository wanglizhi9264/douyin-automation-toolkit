import assert from 'node:assert/strict';
import {taskStage,taskProblem,matchesAuthor} from '../src/sidebar/presentation.js';
assert.equal(taskStage({status:'completed'}),'本轮完成');
assert.equal(taskStage({status:'partial'}),'本轮结束');
assert.equal(taskStage({status:'running'},{running:true}),'检查已有作品');
assert.equal(taskStage({status:'pausing'},{running:true}),'正在暂停');
assert.equal(taskStage({status:'starting'},{running:true}),'正在准备');
assert.equal(taskStage({sourceDone:true},{running:true}),'正在收尾');
assert.equal(taskStage({recovery:{status:'waiting'}},{running:true}),'等待补下');
assert.equal(taskStage({recovery:{status:'running'}},{running:true}),'补下中');
assert.equal(taskStage({},{running:true,active:new Map([['x',{loaded:0}]])}),'准备下载');
assert.equal(taskStage({},{running:true,active:new Map([['x',{loaded:10}]])}),'下载中');
assert.equal(taskStage({},{running:true,retry:{until:Date.now()+1000},active:new Map([['x',{loaded:10}]])}),'下载中','list throttling must not hide media still transferring');
const persisted=JSON.parse(JSON.stringify({status:'paused',sourceErrors:['文件夹授权失效']}));
assert.equal(taskProblem(persisted).action,'folder');
assert.match(taskProblem({sourceErrors:['账号已切换']}).text,/对应的账号/);
assert.match(taskProblem({sourceErrors:['QuotaExceededError']}).text,/空间不足/);
assert.match(taskProblem({sourceErrors:['分页游标异常']}).text,/尚未完整读取/);
assert.match(taskProblem({sourceErrors:['HTTP 429']}).text,/限流/);
assert.equal(taskProblem({sourceErrors:[]}),null,'a manual pause is not an error');
assert.equal(taskProblem({sourceErrors:['旧错误']},'新错误').text,'新错误');
assert.ok(matchesAuthor({nickname:'作者A',uid:'123456'},'345'));
assert.ok(matchesAuthor({nickname:'作者A',uid:'123456'},'  作者a '));
assert.ok(!matchesAuthor({nickname:'作者A',uid:'123456'},'作者B'));
console.log('OK: consistent task stages, persisted pause recovery guidance, manual pause, author name/UID search');
